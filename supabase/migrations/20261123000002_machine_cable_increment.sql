-- =====================================================================
-- Крок ваги в тренажерах і на блоках (machine, cable) — 5 кг:
-- у стеку плит кроку 2.5 кг не буває.
-- Лише системні вправи (owner_id is null): власні вправи користувачів —
-- їхні дані, їх не чіпаємо.
-- Ідемпотентна: можна запускати повторно.
-- =====================================================================
update public.exercises
set weight_increment = 5.0
where owner_id is null
  and equipment in ('machine', 'cable')
  and weight_increment <> 5.0;
